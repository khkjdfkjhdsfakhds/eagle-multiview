'use strict';
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs'); const os = require('node:os'); const path = require('node:path');
const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'eaglemv-review-fixes-'));
app.setPath('userData', userData); app.setPath('cache', path.join(userData, 'cache'));

async function run() {
  await app.whenReady();
  const window = new BrowserWindow({
    show: false, width: 1200, height: 800,
    webPreferences: { contextIsolation: false, nodeIntegration: false, preload: path.join(__dirname, 'review-bugfixes-preload.cjs') }
  });
  await window.loadFile(path.join(__dirname, '../src/index.html'));
  const result = await window.webContents.executeJavaScript(`(async () => {
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const until = async predicate => { for (let i = 0; i < 150; i += 1) { if (predicate()) return; await wait(20); } throw new Error('fixture not ready'); };
    await until(() => document.querySelectorAll('.content-pane .item-card').length === 6);
    const pane = document.querySelector('.content-pane');
    const click = (id, options = {}) => pane.querySelector('.item-card[data-id="' + id + '"]').dispatchEvent(new MouseEvent('click', { bubbles: true, ...options }));
    click('item-1');
    click('item-2', { metaKey: true });
    const beforeTag = [...window.state.selected];
    await addTagToSelection({ ids: beforeTag, tag: '已审核' });
    const afterTag = [...window.state.selected];
    window.state.contextMenu = { ids: beforeTag };
    await executeContextAction('add-tag', { tag: '右键入口' });
    const afterContextTag = [...window.state.selected];
    window.state.copiedTags = ['粘贴入口'];
    await pasteTagsToItems(beforeTag);
    const afterPasteTag = [...window.state.selected];
    await addTagToSelection({ ids: beforeTag, tag: '部分失败' });
    const afterPartialTag = [...window.state.selected];
    navigate({ kind: 'untagged' });
    await until(() => window.state.currentView?.kind === 'untagged' && pane.querySelector('.item-card[data-id="item-3"]'));
    click('item-3');
    click('item-4', { metaKey: true });
    await addTagToSelection({ ids: ['item-3', 'item-4'], tag: '离场' });
    const afterFilteredTag = [...window.state.selected];
    navigate({ kind: 'folder', id: 'target-folder' });
    await until(() => window.state.currentView?.id === 'target-folder' && pane.querySelectorAll('.item-card').length === 6);
    const press = key => document.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true }));
    clearSelection();
    document.body.focus();
    press('ArrowRight');
    const noSelectionRight = [...window.state.selected];
    clearSelection();
    document.body.focus();
    press('ArrowLeft');
    const noSelectionLeft = [...window.state.selected];
    clearSelection();
    document.body.focus();
    press('ArrowDown');
    const noSelectionDown = [...window.state.selected];
    clearSelection();
    document.body.focus();
    press('ArrowUp');
    const noSelectionUp = [...window.state.selected];
    clearSelection();
    click('item-1');
    click('item-3', { metaKey: true });
    pane.querySelector('.item-card[data-id="item-3"]').focus();
    press('ArrowRight');
    const multiFocusRight = [...window.state.selected];
    clearSelection();
    click('item-1');
    click('item-3', { metaKey: true });
    document.body.tabIndex = -1;
    document.body.focus();
    press('ArrowRight');
    const multiWithoutFocusRight = [...window.state.selected];
    const wheelAllowed = async id => {
      await openPreview(id);
      await wait(30);
      const media = pane.querySelector('#modalMedia');
      if (id === 'item-1' && !media.querySelector('img.preview-image')) media.innerHTML = '<img class="preview-image">';
      const before = { id: window.state.previewId, image: Boolean(media.querySelector('img.preview-image')), html: media.innerHTML.slice(0, 80), scale: window.state.panes[0].previewZoom.scale };
      const allowed = media.dispatchEvent(new WheelEvent('wheel', { bubbles: true, cancelable: true, deltaY: 120, clientX: 100, clientY: 100 }));
      const scaleAfter = window.state.panes[0].previewZoom.scale;
      closePreview({ commitSelection: false, skipDiscard: true });
      return { allowed, before, scaleAfter };
    };
    const imageWheel = await wheelAllowed('item-1');
    const textWheel = await wheelAllowed('text-1');
    const pdfWheel = await wheelAllowed('pdf-1');
    const imageWheelAllowed = imageWheel.allowed;
    const textWheelAllowed = textWheel.allowed;
    const pdfWheelAllowed = pdfWheel.allowed;
    navigate({ kind: 'root' });
    await until(() => pane.querySelector('.folder-card[data-open-folder="target-folder"]'));
    const dropExternal = (target, file) => {
      const transfer = { types: ['Files'], files: [typeof file === 'string' ? { fixturePath: file } : file], getData: () => '', dropEffect: 'none' };
      const over = new Event('dragover', { bubbles: true, cancelable: true });
      Object.defineProperty(over, 'dataTransfer', { value: transfer });
      target.dispatchEvent(over);
      const hover = { dropEffect: transfer.dropEffect, highlighted: target.classList.contains('drop-target') };
      const event = new Event('drop', { bubbles: true, cancelable: true });
      Object.defineProperty(event, 'dataTransfer', { value: transfer });
      target.dispatchEvent(event);
      return hover;
    };
    const cardHover = dropExternal(pane.querySelector('.folder-card[data-open-folder="target-folder"]'), '/tmp/card.png');
    await wait(120);
    const treeHover = dropExternal(document.querySelector('.folder-row[data-folder-id="target-folder"]'), '/tmp/tree.png');
    await wait(120);
    window.eagleMV.platform = 'web';
    const webFileHover = dropExternal(pane.querySelector('.folder-card[data-open-folder="target-folder"]'), { name: 'web.png', type: 'image/png', size: 42 });
    await wait(120);
    window.eagleMV.platform = 'darwin';
    navigate({ kind: 'folder', id: 'target-folder' });
    await until(() => window.state.currentView?.id === 'target-folder');
    dropExternal(pane.querySelector('#gridScroller'), '/tmp/pane.png');
    navigate({ kind: 'root' });
    await wait(120);
    const imports = window.__reviewCalls.filter(call => call.kind === 'import');
    return { beforeTag, afterTag, afterContextTag, afterPasteTag, afterPartialTag, afterFilteredTag, noSelectionRight, noSelectionLeft, noSelectionDown, noSelectionUp, multiFocusRight, multiWithoutFocusRight, imageWheelAllowed, textWheelAllowed, pdfWheelAllowed, imports, hovers: { cardHover, treeHover, webFileHover }, wheelDebug: { imageWheel, textWheel, pdfWheel } };
  })()`);
  process.stdout.write(`EAGLEMV_REVIEW_FIXES ${JSON.stringify(result)}\n`);
  window.destroy(); app.quit();
}
run().catch(error => { console.error(error); app.exit(1); });
